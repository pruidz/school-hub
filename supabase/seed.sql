-- Password hashes. pgcrypto normally lives in the "extensions" schema on
-- Supabase; fall back to public, and to "no password" if neither resolves.
do $outer$
declare
  v_pw  text;
  v_pin text;
begin
  begin
    execute $q$ select extensions.crypt('SchoolHub123!', extensions.gen_salt('bf')),
                       extensions.crypt('1234',          extensions.gen_salt('bf')) $q$
      into v_pw, v_pin;
  exception when others then
    begin
      execute $q$ select public.crypt('SchoolHub123!', public.gen_salt('bf')),
                         public.crypt('1234',          public.gen_salt('bf')) $q$
        into v_pw, v_pin;
    exception when others then
      v_pw  := null;
      v_pin := null;
      raise notice 'pgcrypto not reachable — seeded users have no password set.';
    end;
  end;

  update auth.users
     set encrypted_password = v_pw
   where id in ('a0000000-0000-4000-8000-000000000001',
                'a0000000-0000-4000-8000-000000000002',
                'a0000000-0000-4000-8000-000000000003');

  -- stash the PIN hash for step 3
  create temporary table if not exists _seed_pin (pin_hash text);
  delete from _seed_pin;
  insert into _seed_pin values (v_pin);
end;
$outer$;

