/**
 * Concatenate supabase/migrations/*.sql into supabase/APPLY_ALL.sql.
 *
 * The numbered files stay the source of truth — this is a convenience so the
 * whole schema can be applied with one paste into the Supabase SQL editor
 * instead of eleven. Wrapped in a single transaction: a failure anywhere
 * rolls the lot back rather than leaving a half-built database, which is much
 * harder to recover from than starting again.
 *
 *   npm run sql:bundle
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..");
const DIR = path.join(REPO, "supabase", "migrations");
const OUT = path.join(REPO, "supabase", "APPLY_ALL.sql");

const files = fs
  .readdirSync(DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  console.error("no migrations found in", DIR);
  process.exit(1);
}

const lines = [
  "-- =====================================================================",
  "-- SCHOOL-HUB — ALL MIGRATIONS IN ONE FILE",
  "--",
  "-- Generated from supabase/migrations/ — do not edit this file by hand.",
  "-- Regenerate with: npm run sql:bundle",
  "--",
  "-- Paste the whole thing into the Supabase SQL editor and press Run, once.",
  "-- Same statements as the numbered files, same order, wrapped in one",
  "-- transaction so a failure leaves nothing half-applied.",
  "--",
  `-- Files included: ${files.join(", ")}`,
  "-- =====================================================================",
  "",
  "begin;",
  "",
];

for (const f of files) {
  lines.push(
    "-- ---------------------------------------------------------------------",
    `-- ${f}`,
    "-- ---------------------------------------------------------------------",
    fs.readFileSync(path.join(DIR, f), "utf8").replace(/\s+$/, ""),
    "",
  );
}

lines.push("commit;", "");

fs.writeFileSync(OUT, lines.join("\n"), "utf8");
console.log(
  `supabase/APPLY_ALL.sql — ${files.length} migrations, ${lines.length} lines`,
);
